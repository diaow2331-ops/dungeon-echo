'use strict';
const fs = require('fs');
const path = require('path');
const root = process.env.DE_ROOT || path.resolve(__dirname, '..');
const src = fs.readFileSync(path.join(root, 'equipment-shop-ui.js'), 'utf8');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const release = fs.readFileSync(path.join(root, 'ops/release/static-files.txt'), 'utf8');
let pass = 0, fail = 0;
const ok = (cond, name) => { if (cond) { pass++; console.log('  PASS ' + name); } else { fail++; console.log('  FAIL ' + name); } };
ok(src.includes('__DE_EQUIPMENT_SHOP_ART') && src.includes("version:'v3'"), 'shop equipment preview declares scoped event-driven v3');
ok(src.includes('getShopStock()') && src.includes("offer.kind !== 'equip'"), 'only real equipment offers receive preview art');
ok(src.includes('tierArt.sourceForItem(item)'), 'shop preview reuses the tier resolver');
ok(src.includes('[data-buy]') && src.includes("getAttribute('data-buy')"), 'shop rows bind through purchase indexes');
ok(src.includes('new Image()') && src.includes('equipment-weapons-v13.png') && src.includes('equipment-wearables-v13.png'), 'v13 equipment atlases warm before first interaction');
ok(!src.includes('MutationObserver') && !src.includes('requestAnimationFrame') && !src.includes('setInterval'), 'shop preview owns no observer, frame follower or polling loop');
ok(src.includes('const MOVEMENT_KEYS = new Set') && src.includes('function scheduleFromKey'), 'keyboard synchronization is limited to shop state or merchant-entering movement');
ok(src.includes('function scheduleFromClick') && src.includes("target.closest('#game')"), 'map clicks can still synchronize a shop opened by click navigation');
ok(src.includes('queueMicrotask') && src.includes('defer(sync)'), 'shop transition synchronization is deferred to the post-event microtask');
ok(src.includes("api.state === 'shop'") && src.includes('visibilitychange'), 'resume/focus synchronization stays shop-state gated');
ok(/<script src="visual-polish\.js\?v=\d+"><\/script>\s*<script src="equipment-shop-ui\.js\?v=\d+"><\/script>/.test(html), 'shop preview loads after tier art owner with cache-busted assets');
ok(release.includes('equipment-shop-ui.js'), 'release allowlist ships the preview module');
console.log(`\nRESULT  ${pass} passed / ${fail} failed`);
process.exit(fail ? 1 : 0);
