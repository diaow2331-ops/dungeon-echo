'use strict';
const fs=require('fs'),path=require('path'),assert=require('assert');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p));
const text=p=>read(p).toString('utf8');
const game=text('game/core/game.js'),css=text('style.css'),allow=text('ops/release/static-files.txt'),runtime=text('game/core/runtime-bootstrap.js');
const block=(game.match(/const LOOT_ICON_IDS = Object\.freeze\(\[([\s\S]*?)\]\);/)||[])[1];
assert(block,'LOOT_ICON_IDS block missing');
const ids=[...block.matchAll(/'([^']+)'/g)].map(m=>m[1]);
assert.equal(ids.length,31,'production loot atlas must expose 31 live ids');
assert.equal(new Set(ids).size,31,'live loot ids must be unique');
for(const id of ['helm-cloth','helm-iron','helm-knight','helm-dragon','boots-cloth','boots-leather','boots-steel','boots-wind','amulet-copper','amulet-moonstone','amulet-guardian','amulet-abyss']) assert(ids.includes(id),`missing extended slot icon ${id}`);
const png=read('art/loot-atlas.png');
assert(png.subarray(1,4).toString()==='PNG','loot atlas must be PNG');
assert.equal(png.readUInt32BE(16),1024,'admitted atlas width');
assert.equal(png.readUInt32BE(20),2048,'admitted atlas height');
assert(game.includes("lootAtlas.src = 'art/loot-atlas.png'"),'core must own admitted loot atlas');
assert(game.includes('return { x: i % 4, y: Math.floor(i / 4) };'),'core coordinate map must remain 4 columns');
assert(css.includes('background-image: url("art/loot-atlas.png")')&&css.includes('background-size: 400% 800%'),'DOM loot icons must use the same 4x8 atlas');
assert(allow.includes('art/loot-atlas.png'),'admitted loot atlas must ship');
assert(!allow.includes('loot-atlas-v2.svg')&&!runtime.includes('art-runtime-v2.js'),'historical v2 runtime must stay retired');
assert(!game.includes('美术批次待补图集格子'),'stale fallback note must be gone');
console.log('production_loot_atlas_v131=PASS');
