'use strict';
const fs=require('fs'),path=require('path'),assert=require('assert');
const root=path.resolve(__dirname,'..');
const read=file=>fs.readFileSync(path.join(root,file),'utf8');
const town=read('game/ui/town-workspace-v156.js');
const runtime=read('game/core/runtime-bootstrap.js');
const manifest=read('ops/release/static-files.txt');
const bundle=read('ops/release/build-site-bundle.sh');
const deploy=read('ops/site-bundle/deploy.sh');
const health=read('ops/site-bundle/healthcheck.sh');

new Function(town);
new Function(runtime);
assert(town.includes("activeTab = 'gear'"),'town must default to the bounded gear workspace');
for(const tab of ['gear','market','fortune','progress']) assert(town.includes(`data-de-town-tab=\\"${tab}\\"`)||town.includes(`data-de-town-tab="${tab}"`),`missing town tab ${tab}`);
assert(town.includes('height:calc(100dvh - 24px)'),'desktop town must be viewport bounded');
assert(town.includes('overflow:hidden!important'),'town shell must not become a document-length overlay');
assert(town.includes('de-town-item-grid'),'gear must use compact card/grid presentation');
assert(town.includes("renameHide('town-head','town-head-legacy')"),'legacy town head must be hidden from the visible fixed-route workspace');
assert(town.includes("renameHide('town-bag','town-bag-legacy')"),'legacy mixed-locale bag sink must be hidden');
assert(town.includes("renameHide('town-stash','town-stash-legacy')"),'legacy mixed-locale stash sink must be hidden');
assert(town.includes("legacyWheel.id = 'town-wheel-legacy'"),'legacy wheel DOM must stop recreating the visible canvas');
assert(town.includes('https://91hwl.cn/'),'game title/town must expose a main-site return path');
assert(town.includes('https://play.91hwl.cn/moyu/'),'game title/town must expose the other game');
assert(!town.includes('MutationObserver'),'town workspace must not translate with a DOM observer');
assert(!town.includes('setInterval('),'town workspace must not poll');

assert(runtime.includes("const assetVersion = '156'"),'town release must use cache generation 156');
const pScreen=runtime.indexOf('core-screen-owner-v153.js');
const pWorkspace=runtime.indexOf('town-workspace-v156.js');
const pCanvas=runtime.indexOf('town-canvas-locale-v153.js');
assert(pScreen>0&&pWorkspace>pScreen&&pCanvas>pWorkspace,'town workspace must exist before exact canvas localization binds the visible wheel canvas');
assert(manifest.includes('game/ui/town-workspace-v156.js'),'release manifest must ship town workspace');
assert(bundle.includes('asset_generation=156')&&bundle.includes('town-workspace-v156.js'),'bundle must publish generation 156 with town workspace');
assert(deploy.includes('EXPECTED_GENERATION=156')&&deploy.includes('town-workspace-v156.js'),'deployer must require generation 156 town workspace');
assert(health.includes('ASSET_GENERATION=156')&&health.includes('town workspace asset missing'),'healthcheck must prove the workspace asset is live');
console.log('town_workspace_v156=PASS');
